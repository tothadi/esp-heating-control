#!/usr/bin/env python3
"""Generate components/hc_drivers/hc_font.c: a 1-bpp proportional bitmap font for the 128x32 OLED.

Same face and size as the ESPHome build (Roboto Condensed, 14 px). Usage:
    python3 tools/gen_font.py RobotoCondensed-Regular.ttf > components/hc_drivers/hc_font.c
Needs Pillow. Roboto is licensed under the Apache License 2.0.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZE, H = 14, 16
font = ImageFont.truetype(sys.argv[1], SIZE)
ascent, descent = font.getmetrics()
chars = [chr(c) for c in range(32, 127)] + ["°"]
out = ["// Generated by tools/gen_font.py from Roboto Condensed (Apache License 2.0), %d px. Do not edit." % SIZE,
       '#include "hc_font.h"', "", "const hc_glyph_t hc_font_glyphs[HC_FONT_GLYPHS] = {"]
top = max(0, ascent - H + 1) if ascent + descent > H else 0
for ch in chars:
    adv = int(round(font.getlength(ch)))
    w = max(1, min(16, adv))
    img = Image.new("1", (w, H), 0)
    ImageDraw.Draw(img).text((0, -top), ch, font=font, fill=1)
    rows = []
    for y in range(H):
        bits = 0
        for x in range(w):
            if img.getpixel((x, y)):
                bits |= 1 << (15 - x)
        rows.append("0x%04x" % bits)
    name = "deg" if ch == "°" else repr(ch)
    out.append("    {%d, {%s}},  // %s" % (w, ", ".join(rows), name))
out.append("};")
print("\n".join(out))
